def load_capabilities() -> dict:
    """wiki/catalog-capabilities.yaml, checked: the vocabulary the overrides must use."""
    if not CATALOG_CAPABILITIES.exists():
        sys.exit(f"{rel(CATALOG_CAPABILITIES)} is missing; the catalog needs its capability vocabulary")
    doc = yaml.safe_load(CATALOG_CAPABILITIES.read_text(encoding="utf-8")) or {}
    caps = doc.get("capabilities") or {}
    errors = []
    for name, c in caps.items():
        if not CAPABILITY_RE.match(str(name)):
            errors.append(f"capability '{name}': name must be lower-case kebab")
        if not isinstance(c, dict) or not c.get("summary"):
            errors.append(f"capability '{name}': needs a summary")
            continue
        if not c.get("asked_by"):
            errors.append(f"capability '{name}': needs asked_by (which experts resolve it)")
        for skill in c.get("asked_by") or []:
            if not (SKILLS_ROOT / skill / "SKILL.md").is_file():
                errors.append(f"capability '{name}': asked_by names no skill at plugins/forjate/skills/{skill}")
        if c.get("floor") and not c.get("exclusive"):
            errors.append(f"capability '{name}': floor only makes sense on an exclusive capability")
    for skill in doc.get("snapshot_all") or []:
        if not (SKILLS_ROOT / skill / "SKILL.md").is_file():
            errors.append(f"snapshot_all names no skill at plugins/forjate/skills/{skill}")
    if errors:
        sys.exit(f"{rel(CATALOG_CAPABILITIES)}:\n  " + "\n  ".join(errors))
    return doc


def normalize_secrets(value) -> dict:
    """`secrets` used to be a scalar (how a component takes credentials); it is a mapping now."""
    if value is None:
        return {"takes": "unknown"}
    if not isinstance(value, dict):
        return {"takes": str(value)}
    out = dict(value)
    out.setdefault("takes", "unknown")
    return out


def derive_psa_and_namespace(pages: list[Page]) -> dict[str, dict]:
    """Per component page: the PSA level its pods meet and the namespace it runs in, read from the
    tree and aggregated over the sub-components it composes (the least strict level wins; a
    namespace the children agree on is the parent's unless the parent sets its own)."""
    by_src = {rel(p.source): p for p in pages}
    memo: dict[str, dict] = {}

    def walk(src: str, seen: frozenset) -> dict:
        if src in memo:
            return memo[src]
        p = by_src[src]
        levels = list(p.pod_levels)
        unknown = p.helm or (bool(p.remote_refs) and not levels)
        remote = p.helm or bool(p.remote_refs)
        declared = set(p.declared_namespaces)
        own = p.namespace or (p.resource_namespaces[0] if len(p.resource_namespaces) == 1 else None)
        child_ns = set()
        for ref in p.local_refs:
            if ref in by_src and ref not in seen and by_src[ref].kind == "component":
                c = walk(ref, seen | {src})
                levels += c["levels"]
                unknown = unknown or c["unknown"]
                remote = remote or c["remote"]
                declared |= c["declared"]
                if c["namespace"]:
                    child_ns.add(c["namespace"])
        ns = own or (child_ns.pop() if len(child_ns) == 1 else None)
        memo[src] = {"levels": levels, "unknown": unknown, "remote": remote, "declared": declared, "namespace": ns}
        return memo[src]

    out = {}
    for p in pages:
        if p.kind == "component":
            d = walk(rel(p.source), frozenset())
            if d["unknown"]:
                level = "unknown"
            elif not d["levels"]:
                level = "n/a"
            else:
                level = min(d["levels"], key=PSA_LEVELS.index)
            out[rel(p.source)] = {"psa_level": level, "namespace": d["namespace"], "declared": d["declared"], "remote": d["remote"]}
    return out


# Port names that spell their protocol; anything else (client, api, ui, metrics) is not a protocol.
PORT_NAME_PROTOCOLS = {"http", "https", "grpc", "amqp", "mongodb", "postgresql", "redis", "nats", "mqtt", "s3", "tcp", "udp"}


def derive_wiring(pages: list[Page]) -> dict[str, dict]:
    """Per component page: the wiring facts aggregated over the sub-components it composes, in
    page order (the parent's manifests first, then each child's)."""
    by_src = {rel(p.source): p for p in pages}
    memo: dict[str, dict] = {}

    def walk(src: str, seen: frozenset) -> dict:
        if src in memo:
            return memo[src]
        p = by_src[src]
        t = {k: (list(v) if isinstance(v, list) else dict(v)) for k, v in p.wiring_tree.items()} if p.wiring_tree else scan_wiring([], p.source)
        for ref in p.local_refs:
            if ref in by_src and ref not in seen and by_src[ref].kind == "component":
                c = walk(ref, seen | {src})
                for k in ("services", "workloads", "secret_refs", "configmap_refs", "shipped_configmaps", "ingresses"):
                    t[k] = t[k] + [x for x in c[k] if x not in t[k]]
                for k in ("shipped_secrets", "example_keys", "example_literals", "ref_keys"):
                    t[k] = {**c[k], **t[k]}
        memo[src] = t
        return t

    return {rel(p.source): walk(rel(p.source), frozenset()) for p in pages if p.kind == "component"}


def merge_wiring(path: str, extra: dict, t: dict, cur: dict) -> list[str]:
    """Fill `wiring` from the tree, with the curated `wiring:` of catalog-overrides.yaml winning where the
    manifests cannot say (the protocol, laptop sizing, a Secret the component takes but documents nowhere,
    the Service of a bundle that ships several). A curated service or secret the tree contradicts is an error.

    service, port, label: the component's Service (the one named like the component, else the only one),
    its first port, its pod selector's `app`. protocol: the port's name when it spells one, else curated,
    else tcp. workload: the first Deployment, StatefulSet or Pod. secret: the Secret the overlay supplies,
    the first one a pod references that the component does not ship as a shipped-and-kept object, with the
    keys the component documents (a shipped placeholder, an unlisted secret.yaml, a *.env.example).
    placeholder_secrets: Secrets the component ships that a pod references (replaced from Walk).
    config: a ConfigMap a pod references and nobody ships, with the literals its *.env.example documents.
    ingress: the first Ingress. gpu_limit and hostpath: what a Crawl overlay has to patch away on a laptop."""
    errors: list[str] = []
    cw = dict(cur.get("wiring") or {})
    short = path.rsplit("/", 1)[-1]
    services = t.get("services") or []
    svc = None
    if cw.get("service"):
        svc = next((x for x in services if x["name"] == cw["service"]), None)
        if services and svc is None:
            errors.append(f"{path}: wiring.service '{cw['service']}' but its manifests ship {[x['name'] for x in services]}")
    elif len(services) == 1:
        svc = services[0]
    elif services:
        svc = next((x for x in services if x["name"] in (short, f"{short}-service", f"{short}-svc") or (x.get("selector") or {}).get("app") in (short, f"{short}-service")), None)
    port = cw.get("port")
    port_name = None
    if svc and svc["ports"]:
        chosen = next((p for p in svc["ports"] if port is not None and p.get("port") == port), svc["ports"][0])
        port = port if port is not None else chosen.get("port")
        port_name = chosen.get("name")
    protocol = cw.get("protocol") or (port_name if port_name in PORT_NAME_PROTOCOLS else None) or "tcp"
    label = cw.get("label") or ((svc or {}).get("selector") or {}).get("app") or ((t.get("workloads") or [{}])[0].get("name") if t.get("workloads") else None)
    workloads = t.get("workloads") or []
    main = next((w for w in workloads if w["kind"] in ("Deployment", "StatefulSet")), workloads[0] if workloads else None)
    if cw.get("workload"):
        main = next((w for w in workloads if w["name"] == cw["workload"]), main)
    shipped = t.get("shipped_secrets") or {}
    placeholders = [n for n in (t.get("secret_refs") or []) if n in shipped]
    secret = None
    if "secret" in cw:
        secret = cw["secret"]
        if secret and secret.get("name") and (t.get("secret_refs") or []) and secret["name"] not in t["secret_refs"] and main is not None and main["kind"] != "Pod":
            errors.append(f"{path}: wiring.secret '{secret['name']}' but its pods reference {t['secret_refs']}")
    else:
        for n in t.get("secret_refs") or []:
            if n in shipped and extra.get("namespace"):
                continue  # shared infrastructure ships its own credentials in its own namespace; not the overlay's to supply
            keys = (t.get("example_keys") or {}).get(n) or shipped.get(n) or (t.get("ref_keys") or {}).get(n)
            if keys:
                secret = {"name": n, "keys": list(keys)}
                break
        if secret is None:
            own = [n for n in t.get("secret_refs") or [] if not (n in shipped and extra.get("namespace"))]
            if own:
                secret = {"name": own[0], "keys": []}  # the overlay supplies it; the keys are curated or written by hand
    config = None
    if "config" in cw:
        config = cw["config"]
    else:
        for n in t.get("configmap_refs") or []:
            if n not in (t.get("shipped_configmaps") or []):
                config = {"name": n, "literals": list((t.get("example_literals") or {}).get(n) or [])}
                break
    extra["wiring"] = {
        "service": (svc or {}).get("name") or cw.get("service"),
        "port": port,
        "protocol": protocol,
        "label": label,
        "workload": {"kind": main["kind"], "name": main["name"], "container": main.get("container")} if main else None,
        "secret": secret,
        "placeholder_secrets": placeholders,
        "config": config,
        "ingress": cw.get("ingress") or ((t.get("ingresses") or [None])[0]),
        "gpu_limit": any(w.get("gpu") for w in workloads),
        "hostpath": any(w.get("hostpath") for w in workloads),
        "hostpath_volumes": [dict(v, workload=w["name"], kind=w["kind"]) for w in workloads for v in w.get("hostpath_volumes") or []],
        "secret_mounted": bool(secret) and secret.get("name") in (t.get("secret_refs") or []),
        "sizing": cw.get("sizing"),
        "extra_ports": cw.get("extra_ports") or {},
    }
    return errors


def merge_psa_and_namespace(path: str, extra: dict, d: dict, cur: dict) -> list[str]:
    """Fill `psa_level`, `namespace` and `namespace_how` from the tree; a curated value wins, but a
    curation the tree contradicts is an error, so a component that changes its namespace or gains
    host access cannot keep a stale override. namespace_how: declares (ships the Namespace) | remote
    (Helm or remote manifests carry it; whether they ship the Namespace is not readable here) | sets
    (its manifests use it, nobody in it declares it) | none (the overlay has to place it)."""
    errors = []
    tree_level = d["psa_level"]
    if "psa_level" in cur:
        level = cur["psa_level"]
        if level not in PSA_LEVELS + ("n/a", "unknown"):
            errors.append(f"{path}: psa_level '{level}' is not one of {', '.join(PSA_LEVELS)}, n/a, unknown")
    elif extra.get("psa_restricted") is True:
        level = "restricted"
    elif tree_level == "restricted" and extra.get("psa_restricted") is False:
        level = "baseline"
    else:
        level = tree_level
    if extra.get("psa_restricted") is True and tree_level == "privileged":
        errors.append(f"{path}: psa_restricted is true but its manifests need host access (privileged)")
    extra["psa_level"] = level

    tree_ns = d["namespace"]
    if "namespace" in cur:
        ns = cur["namespace"]
        if ns is not None and tree_ns is not None and ns != tree_ns:
            errors.append(f"{path}: namespace override '{ns}' but its manifests set '{tree_ns}'")
    else:
        ns = tree_ns
    extra["namespace"] = ns
    if ns is None:
        extra["namespace_how"] = None
    elif ns in d["declared"]:
        extra["namespace_how"] = "declares"
    elif d["remote"]:
        extra["namespace_how"] = "remote"
    elif tree_ns == ns:
        extra["namespace_how"] = "sets"
    else:
        extra["namespace_how"] = "none"
    return errors


def build_catalog(pages: list[Page], compiled_at: str) -> dict:
    """wiki/catalog.json as a dict — one record per component, merged with curated overrides.

    This is the machine-readable catalog the use-case builder experts query
    (plugins/forjate). Declared facts come from the tree; stage fitness,
    capabilities, properties, licence and maturity come from catalog-overrides.yaml;
    the capability vocabulary from catalog-capabilities.yaml.
    """
    overrides = {"defaults": {}, "components": {}}
    if CATALOG_OVERRIDES.exists():
        overrides = yaml.safe_load(CATALOG_OVERRIDES.read_text(encoding="utf-8")) or overrides
    defaults = overrides.get("defaults") or {}
    curated = overrides.get("components") or {}
    vocab = load_capabilities()
    caps = vocab.get("capabilities") or {}

    comps_root = K8S / "components"
    records = []
    errors = []
    derived = derive_psa_and_namespace(pages)
    wiring = derive_wiring(pages)
    for p in pages:
        if p.kind != "component":
            continue
        path = str(p.source.relative_to(comps_root))
        rec = {
            "path": path,
            "name": p.name,
            "category": p.category,
            "wiki": rel(p.out),
            "summary": p.summary,
            "images": p.images,
            "kinds": p.kinds,
            "composes": p.local_refs,
            "remote_refs": p.remote_refs,
            "consumed_by": p.consumed_by,
            "parent": p.parent,
        }
        extra = dict(defaults)
        extra.update(curated.get(path) or {})
        extra["curated"] = path in curated
        extra["secrets"] = normalize_secrets(extra.get("secrets"))
        if "roles" in extra:
            errors.append(f"{path}: `roles` was renamed `capabilities`")
        for cap in extra.get("capabilities") or []:
            if cap not in caps:
                errors.append(f"{path}: unknown capability '{cap}' (define it in {rel(CATALOG_CAPABILITIES)})")
        if extra["secrets"].get("mechanism") and "secrets-mechanism" not in (extra.get("capabilities") or []):
            errors.append(f"{path}: secrets.mechanism is only for components with the secrets-mechanism capability")
        errors += merge_psa_and_namespace(path, extra, derived[rel(p.source)], curated.get(path) or {})
        errors += merge_wiring(path, extra, wiring[rel(p.source)], curated.get(path) or {})
        rec.update(extra)
        records.append(rec)
    if errors:
        sys.exit(f"{rel(CATALOG_OVERRIDES)}:\n  " + "\n  ".join(errors))

    unknown = sorted(set(curated) - {r["path"] for r in records})
    return {
        "apiVersion": "forjate.io/v0",
        "kind": "Catalog",
        "compiled_at": compiled_at,
        "stages": ["crawl", "walk", "run"],
        "capabilities": caps,
        "snapshot_all": vocab.get("snapshot_all") or [],
        "components": records,
        "overrides_without_component": unknown,
    }


