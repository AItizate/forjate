#!/usr/bin/env python3
"""Compile the Forjate wiki from the Kustomize tree.

The Kustomize tree under k8s/ is the source of truth. This script derives one
page per component, overlay and base app, filling the "Declared" zone with facts
read straight out of the YAML and computing consumed_by backlinks from real
references (resources:, components:, transformers:, generators:, validators:).

The "Notes" zone of every page is preserved verbatim across runs, so prose
written by a human or an agent survives recompilation.

See wiki/SCHEMA.md for the conventions this script implements.

Usage:
    poetry run python scripts/wiki-compile.py [--check]

    --check   report what would change without writing (for CI)
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("pyyaml is required. Run: poetry install")

REPO = Path(__file__).resolve().parent.parent
K8S = REPO / "k8s"
WIKI = REPO / "wiki"

DECLARED_BEGIN = "<!-- BEGIN DECLARED (generated by scripts/wiki-compile.py — do not edit) -->"
DECLARED_END = "<!-- END DECLARED -->"
NOTES_HEADING = "## Notes"

NOTES_PLACEHOLDER = (
    "_No notes yet. This zone is for interpretation: what this is for, how it\n"
    "composes with others, gotchas. It survives recompilation — write freely._"
)

IMAGE_RE = re.compile(r"^\s*(?:-\s+)?image:\s*[\"']?([^\"'\s]+)", re.MULTILINE)
REMOTE_RE = re.compile(r"^(https?://|ssh://|git@|github\.com/)")

# Kustomization fields whose entries can name another kustomization, and how the
# consumer pulls it in. `bases:` is the deprecated spelling of `resources:`.
REF_FIELDS = (("resources", "resource"), ("bases", "resource"),
              ("components", "component"), ("transformers", "transformer"),
              ("generators", "generator"), ("validators", "validator"))


@dataclass
class Page:
    """One compiler-owned wiki page derived from a directory in k8s/."""

    name: str
    kind: str                      # component | overlay | base
    category: str | None
    source: Path                   # absolute path to the source directory
    rel_source: str                # repo-relative, goes into frontmatter
    out: Path                      # absolute path of the wiki page

    header: str = ""               # leading comment block of kustomization.yaml
    resources: list[str] = field(default_factory=list)
    declared: dict = field(default_factory=dict)          # components:/transformers:/... verbatim
    local_refs: list[str] = field(default_factory=list)   # resolved sibling dirs
    ref_how: dict = field(default_factory=dict)           # local ref -> "component", "resource, via ..."
    remote_refs: list[str] = field(default_factory=list)
    images: list[str] = field(default_factory=list)
    kinds: list[str] = field(default_factory=list)        # k8s kinds declared
    labels: dict = field(default_factory=dict)
    patches: list[str] = field(default_factory=list)
    configmaps: list[str] = field(default_factory=list)
    secrets: list[str] = field(default_factory=list)
    namespace: str | None = None
    helm: bool = False             # renders a Helm chart: its pods are not in the listed files
    pod_levels: list[str] = field(default_factory=list)   # PSA level each scanned pod template meets
    resource_namespaces: list[str] = field(default_factory=list)  # metadata.namespace of the listed resources
    declared_namespaces: list[str] = field(default_factory=list)  # Namespace objects it ships
    wiring_tree: dict = field(default_factory=dict)       # services, workloads, secrets, configmaps, ingresses read from the manifests
    parent: str | None = None      # set when nested inside another kustomization
    summary: str = ""             # one-liner used by index.md
    consumed_by: list[str] = field(default_factory=list)  # computed backlinks
    consumed_how: dict = field(default_factory=dict)      # consumer link -> how it consumes
    depends_on: dict = field(default_factory=dict)        # local ref -> link of its page
    warnings: list[str] = field(default_factory=list)


def rel(p: Path) -> str:
    return str(p.relative_to(REPO))


def load_kustomization(path: Path) -> tuple[dict, str, list[str]]:
    """Return (parsed doc, leading comment block, warnings)."""
    warnings: list[str] = []
    text = path.read_text(encoding="utf-8")

    header_lines = []
    after_keys = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            header_lines.append(stripped.lstrip("#").strip())
        elif not stripped:
            if header_lines:
                header_lines.append("")
        elif header_lines:
            # Below apiVersion/kind, a comment glued to the next key labels that
            # key ("# Set the namespace" over namespace:), it does not describe
            # the kustomization: keep only the paragraphs before it.
            if after_keys and header_lines[-1] != "":
                cut = max((i for i, l in enumerate(header_lines) if l == ""), default=0)
                header_lines = header_lines[:cut]
            break
        elif stripped.startswith(("apiVersion:", "kind:")):
            # The descriptive comment may sit above or below these two.
            after_keys = True
        else:
            break
    header = "\n".join(header_lines).strip()

    try:
        doc = yaml.safe_load(text) or {}
    except yaml.YAMLError as exc:
        warnings.append(f"kustomization.yaml did not parse: {exc}")
        doc = {}
    if not isinstance(doc, dict):
        warnings.append("kustomization.yaml is not a mapping")
        doc = {}
    return doc, header, warnings


def scan_manifests(files: list[Path]) -> tuple[list[str], list[str]]:
    """Collect container images and Kubernetes kinds from the files a
    kustomization lists. Only listed files: patches, a sub-page's manifests and
    a `kustomize build --enable-helm` charts/ cache are not declared here."""
    images: set[str] = set()
    kinds: set[str] = set()
    for f in sorted(set(files)):
        if f.suffix not in (".yaml", ".yml"):
            continue
        try:
            text = f.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        images.update(IMAGE_RE.findall(text))
        try:
            for doc in yaml.safe_load_all(text):
                if isinstance(doc, dict) and isinstance(doc.get("kind"), str):
                    kinds.add(doc["kind"])
        except yaml.YAMLError:
            pass
    return sorted(images), sorted(kinds)


# Pod Security Standards, read from the pod templates a component ships. `privileged` when a
# pod needs host access the baseline profile forbids; `restricted` when every container meets
# the restricted profile; `baseline` otherwise. https://kubernetes.io/docs/concepts/security/pod-security-standards/
PSA_LEVELS = ("privileged", "baseline", "restricted")
BASELINE_CAPS = {"AUDIT_WRITE", "CHOWN", "DAC_OVERRIDE", "FOWNER", "FSETID", "KILL", "MKNOD", "NET_BIND_SERVICE",
                 "SETFCAP", "SETGID", "SETPCAP", "SETUID", "SYS_CHROOT"}
CLUSTER_SCOPED = {"Namespace", "ClusterRole", "ClusterRoleBinding", "CustomResourceDefinition", "StorageClass",
                  "PersistentVolume", "PriorityClass", "MutatingWebhookConfiguration", "ValidatingWebhookConfiguration",
                  "IngressClass", "CSIDriver", "APIService", "ClusterIssuer", "ClusterSecretStore", "RuntimeClass"}


def pod_spec(doc: dict) -> dict | None:
    kind, spec = doc.get("kind"), doc.get("spec") or {}
    if kind == "Pod":
        return spec
    if kind in ("Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Job"):
        return (spec.get("template") or {}).get("spec")
    if kind == "CronJob":
        return (((spec.get("jobTemplate") or {}).get("spec") or {}).get("template") or {}).get("spec")
    return None


def pod_psa_level(ps: dict) -> str:
    """The strictest Pod Security Standard a pod spec meets."""
    if ps.get("hostNetwork") or ps.get("hostPID") or ps.get("hostIPC"):
        return "privileged"
    if any("hostPath" in (v or {}) for v in ps.get("volumes") or []):
        return "privileged"
    psc = ps.get("securityContext") or {}
    if ((psc.get("seccompProfile") or {}).get("type")) == "Unconfined":
        return "privileged"
    restricted = True
    for c in (ps.get("containers") or []) + (ps.get("initContainers") or []):
        sc = (c or {}).get("securityContext") or {}
        caps = sc.get("capabilities") or {}
        added = {str(x).upper() for x in caps.get("add") or []}
        if sc.get("privileged") or added - BASELINE_CAPS or any((pt or {}).get("hostPort") for pt in c.get("ports") or []):
            return "privileged"
        if ((sc.get("seccompProfile") or {}).get("type")) == "Unconfined":
            return "privileged"
        seccomp = (sc.get("seccompProfile") or psc.get("seccompProfile") or {}).get("type")
        non_root = sc.get("runAsNonRoot", psc.get("runAsNonRoot"))
        drops = {str(x).upper() for x in caps.get("drop") or []}
        if not (non_root is True and sc.get("allowPrivilegeEscalation") is False and "ALL" in drops
                and seccomp in ("RuntimeDefault", "Localhost") and added <= {"NET_BIND_SERVICE"}):
            restricted = False
    return "restricted" if restricted else "baseline"


def scan_pods_and_namespaces(files: list[Path]) -> tuple[list[str], list[str], list[str]]:
    """(PSA level per pod template, metadata.namespace of the namespaced resources, Namespace objects)."""
    levels: list[str] = []
    namespaces: set[str] = set()
    declared: set[str] = set()
    for f in sorted(set(files)):
        if f.suffix not in (".yaml", ".yml"):
            continue
        try:
            docs = list(yaml.safe_load_all(f.read_text(encoding="utf-8")))
        except (OSError, UnicodeDecodeError, yaml.YAMLError):
            continue
        for doc in docs:
            if not isinstance(doc, dict) or not isinstance(doc.get("kind"), str):
                continue
            meta = doc.get("metadata") or {}
            if doc["kind"] == "Namespace" and meta.get("name"):
                declared.add(str(meta["name"]))
            elif doc["kind"] not in CLUSTER_SCOPED and meta.get("namespace"):
                namespaces.add(str(meta["namespace"]))
            ps = pod_spec(doc)
            if isinstance(ps, dict):
                levels.append(pod_psa_level(ps))
    return levels, sorted(namespaces), sorted(declared)


def scan_wiring(files: list[Path], directory: Path) -> dict:
    """What an overlay needs to wire a component, read from the manifests it lists: its Services
    (name, ports, pod selector), its workloads (kind, name, first container, ports, GPU request,
    hostPath volumes), the Secrets and ConfigMaps its pods reference, the Secrets and ConfigMaps
    it ships (placeholders the overlay replaces), its Ingresses, and the keys its `*.env.example`
    files and unlisted `secret*.yaml` document for the Secrets the overlay must supply."""
    out = {"services": [], "workloads": [], "secret_refs": [], "configmap_refs": [], "shipped_secrets": {},
           "shipped_configmaps": [], "ingresses": [], "example_keys": {}, "example_literals": {}, "ref_keys": {}}

    def ordered_keys(doc: dict) -> list[str]:
        keys = list((doc.get("data") or {}).keys()) + list((doc.get("stringData") or {}).keys())
        return list(dict.fromkeys(str(k) for k in keys))
    for f in sorted(set(files)):
        if f.suffix not in (".yaml", ".yml"):
            continue
        try:
            docs = list(yaml.safe_load_all(f.read_text(encoding="utf-8")))
        except (OSError, UnicodeDecodeError, yaml.YAMLError):
            continue
        for doc in docs:
            if not isinstance(doc, dict) or not isinstance(doc.get("kind"), str):
                continue
            kind, meta, spec = doc["kind"], doc.get("metadata") or {}, doc.get("spec") or {}
            name = meta.get("name")
            if kind == "Service" and name:
                ports = [{"name": p.get("name"), "port": p.get("port")} for p in spec.get("ports") or [] if isinstance(p, dict)]
                out["services"].append({"name": name, "ports": ports, "selector": spec.get("selector") or {}})
            elif kind == "Secret" and name:
                out["shipped_secrets"][name] = ordered_keys(doc)
            elif kind == "ConfigMap" and name:
                out["shipped_configmaps"].append(name)
            elif kind == "Ingress" and name:
                out["ingresses"].append(name)
            ps = pod_spec(doc)
            if isinstance(ps, dict) and name:
                cts = ps.get("containers") or []
                first = cts[0] if cts else {}
                res = first.get("resources") or {}
                w = {"kind": kind, "name": name, "container": first.get("name"),
                     "ports": [p.get("containerPort") for p in first.get("ports") or [] if isinstance(p, dict)],
                     "gpu": any("nvidia.com/gpu" in (res.get(k) or {}) for k in ("limits", "requests")),
                     "hostpath": any("hostPath" in v for v in ps.get("volumes") or [] if isinstance(v, dict)),
                     "hostpath_volumes": [{"index": i, "name": v.get("name")} for i, v in enumerate(ps.get("volumes") or []) if isinstance(v, dict) and "hostPath" in v],
                     "has_resources": bool(res)}
                out["workloads"].append(w)
                for ct in cts:
                    for e in ct.get("envFrom") or []:
                        if isinstance(e, dict) and (e.get("secretRef") or {}).get("name"):
                            out["secret_refs"].append(e["secretRef"]["name"])
                        if isinstance(e, dict) and (e.get("configMapRef") or {}).get("name"):
                            out["configmap_refs"].append(e["configMapRef"]["name"])
                    for e in ct.get("env") or []:
                        ref = ((e.get("valueFrom") or {}).get("secretKeyRef") or {}) if isinstance(e, dict) else {}
                        if ref.get("name"):
                            out["secret_refs"].append(ref["name"])
                            if ref.get("key") and ref["key"] not in out["ref_keys"].setdefault(ref["name"], []):
                                out["ref_keys"][ref["name"]].append(str(ref["key"]))
    out["secret_refs"] = list(dict.fromkeys(out["secret_refs"]))
    out["configmap_refs"] = list(dict.fromkeys(out["configmap_refs"]))
    # keys the component documents for the Secrets and ConfigMaps the overlay supplies
    for f in sorted(directory.glob("*.env.example")):
        lines = [ln.strip() for ln in f.read_text(encoding="utf-8", errors="replace").splitlines()
                 if ln.strip() and not ln.lstrip().startswith("#") and "=" in ln]
        out["example_keys"][f.name[: -len(".env.example")]] = [ln.split("=", 1)[0].strip() for ln in lines]
        out["example_literals"][f.name[: -len(".env.example")]] = lines
    for f in sorted(directory.glob("secret*.yaml")):
        if f in set(files):
            continue
        try:
            for doc in yaml.safe_load_all(f.read_text(encoding="utf-8")):
                if isinstance(doc, dict) and doc.get("kind") == "Secret" and (doc.get("metadata") or {}).get("name"):
                    out["example_keys"].setdefault(doc["metadata"]["name"], ordered_keys(doc))
        except (OSError, UnicodeDecodeError, yaml.YAMLError):
            continue
    return out


def collect_refs(page: Page, directory: Path, doc: dict, page_dirs: set[Path],
                 files: list[Path], via: str | None = None) -> None:
    """Record what a kustomization references. A directory inside the page that
    is not a page of its own (namespaces/x) is part of the page: it is walked,
    and what it references counts as referenced by the page."""
    for key, how in REF_FIELDS:
        for r in doc.get(key, []) or []:
            # transformers:/generators: also take inline objects, which name nothing.
            if not isinstance(r, str):
                continue
            if REMOTE_RE.match(r):
                page.remote_refs.append(r)
                continue
            target = (directory / r).resolve()
            if target.is_file():
                files.append(target)
            elif target.is_dir() and K8S in target.parents:
                sub = target / "kustomization.yaml"
                if target not in page_dirs and page.source in target.parents and sub.exists():
                    subdoc, _, warnings = load_kustomization(sub)
                    page.warnings.extend(f"{rel(sub)}: {w}" for w in warnings)
                    collect_refs(page, target, subdoc, page_dirs, files,
                                 via=str(target.relative_to(page.source)))
                    continue
                ref = rel(target)
                if ref not in page.ref_how:
                    page.local_refs.append(ref)
                    page.ref_how[ref] = how + (f", via {via}" if via else "")


def extract(page: Page, page_dirs: set[Path]) -> None:
    kfile = page.source / "kustomization.yaml"
    if not kfile.exists():
        page.warnings.append("no kustomization.yaml in this directory")
        return

    doc, header, warnings = load_kustomization(kfile)
    page.header = header
    page.warnings.extend(warnings)

    page.namespace = doc.get("namespace")

    for key, _ in REF_FIELDS:
        entries = [r for r in doc.get(key, []) or [] if isinstance(r, str)]
        if key in ("resources", "bases"):
            page.resources.extend(entries)
        elif entries:
            page.declared[key] = entries

    files: list[Path] = []
    collect_refs(page, page.source, doc, page_dirs, files)

    for lbl in doc.get("labels", []) or []:
        if isinstance(lbl, dict):
            page.labels.update(lbl.get("pairs", {}) or {})
    if isinstance(doc.get("commonLabels"), dict):
        page.labels.update(doc["commonLabels"])

    for p in doc.get("patches", []) or []:
        if isinstance(p, dict):
            target = p.get("target", {}) or {}
            desc = target.get("kind", "?")
            if target.get("name"):
                desc += f"/{target['name']}"
            if target.get("namespace"):
                desc += f" (ns: {target['namespace']})"
            page.patches.append(f"{p.get('path', 'inline')} → {desc}")

    for gen, bucket in (("configMapGenerator", page.configmaps),
                        ("secretGenerator", page.secrets)):
        for entry in doc.get(gen, []) or []:
            if isinstance(entry, dict) and entry.get("name"):
                ns = entry.get("namespace")
                bucket.append(f"{entry['name']}" + (f" (ns: {ns})" if ns else ""))

    page.images, page.kinds = scan_manifests(files)
    page.helm = bool(doc.get("helmCharts"))
    helm_ns = {h["namespace"] for h in doc.get("helmCharts") or [] if isinstance(h, dict) and h.get("namespace")}
    page.pod_levels, page.resource_namespaces, page.declared_namespaces = scan_pods_and_namespaces(files)
    page.resource_namespaces = sorted(set(page.resource_namespaces) | helm_ns)
    page.wiring_tree = scan_wiring(files, page.source)


# Directories that are structural parts of a kustomization, never pages of their own.
STRUCTURAL = {"namespaces", "patches", "configs", "secrets", "templates", "relocated", "wrapped"}


def is_page_dir(d: Path, root: Path) -> bool:
    """A directory earns a page if it declares a kustomization and is not a
    structural sub-directory of one (patches/, secrets/, namespaces/, ...)."""
    if not (d / "kustomization.yaml").exists():
        return False
    return not any(part in STRUCTURAL for part in d.relative_to(root).parts)


def discover() -> list[Page]:
    pages: list[Page] = []
    seen: dict[Path, Page] = {}

    # Components: everything under k8s/components, not just apps/.
    comps = K8S / "components"
    if comps.is_dir():
        for kfile in sorted(comps.rglob("kustomization.yaml")):
            d = kfile.parent
            if not is_page_dir(d, comps):
                continue
            parts = d.relative_to(comps).parts
            # apps/databases/postgres -> category "databases", name "databases-postgres"
            # bundles/temporal-stack  -> category "bundles",   name "bundles-temporal-stack"
            if parts[0] == "apps":
                rest = parts[1:]
                category = rest[0] if len(rest) > 1 else "standalone"
            else:
                rest = parts
                category = parts[0]
            if not rest:
                continue
            page = Page(
                name="-".join(rest), kind="component", category=category,
                source=d, rel_source=rel(d),
                out=WIKI / "components" / f"{'-'.join(rest)}.md",
            )
            pages.append(page)
            seen[d] = page

    # Overlays, including nested ones (multi-tenant-pattern/tenants/client-a).
    overlays = K8S / "overlays"
    if overlays.is_dir():
        for kfile in sorted(overlays.rglob("kustomization.yaml")):
            d = kfile.parent
            if not is_page_dir(d, overlays):
                continue
            parts = d.relative_to(overlays).parts
            page = Page(
                name="-".join(parts), kind="overlay",
                category=parts[0] if len(parts) > 1 else None,
                source=d, rel_source=rel(d),
                out=WIKI / "overlays" / f"{'-'.join(parts)}.md",
            )
            pages.append(page)
            seen[d] = page

    base = K8S / "base"
    if (base / "kustomization.yaml").exists():
        page = Page(name="base", kind="base", category=None,
                    source=base, rel_source=rel(base),
                    out=WIKI / "base" / "base.md")
        pages.append(page)
        seen[base] = page
    for d in sorted(p for p in (base / "apps").glob("*") if p.is_dir()):
        if (d / "kustomization.yaml").exists():
            page = Page(name=d.name, kind="base", category="base-app",
                        source=d, rel_source=rel(d),
                        out=WIKI / "base" / f"{d.name}.md")
            pages.append(page)
            seen[d] = page

    # Nesting: a page whose enclosing directory is also a page is a sub-page.
    for page in pages:
        for ancestor in page.source.parents:
            if ancestor in seen:
                page.parent = link_for(seen[ancestor])
                break
            if ancestor == K8S:
                break

    return pages


def link_for(page: Page) -> str:
    return f"{page.out.parent.name}/{page.out.stem}"


def compute_backlinks(pages: list[Page]) -> None:
    """consumed_by is derived from real references (resources:, components:,
    transformers:, ...), never hand-written."""
    by_source = {p.rel_source: p for p in pages}
    for page in pages:
        for ref in page.local_refs:
            target = by_source.get(ref)
            if target and target is not page:
                target.consumed_how.setdefault(link_for(page), page.ref_how[ref])
                page.depends_on[ref] = link_for(target)
    for page in pages:
        page.consumed_by = sorted(page.consumed_how)


def compile_pages() -> list[Page]:
    """Discover every page and fill in its facts and backlinks."""
    pages = discover()
    page_dirs = {p.source for p in pages}
    for page in pages:
        extract(page, page_dirs)
    compute_backlinks(pages)
    return pages


def read_frontmatter(path: Path) -> dict:
    """The YAML frontmatter of a wiki page, or {} when it has none."""
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    try:
        fm = yaml.safe_load(text[3:end])
    except yaml.YAMLError:
        return {}
    return fm if isinstance(fm, dict) else {}


def how_note(how: str) -> str:
    """Plain resources are the default and go unlabelled."""
    return "" if how == "resource" else f" — {how}"


def source_last_commit(rel_path: str) -> str | None:
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", rel_path],
            cwd=REPO, capture_output=True, text=True, timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    value = out.stdout.strip()
    return value or None


def bullets(items: list[str], empty: str = "_none declared_") -> str:
    if not items:
        return empty
    return "\n".join(f"- `{i}`" for i in items)


def render_declared(page: Page) -> str:
    lines: list[str] = []

    if page.header:
        lines += ["> Source comment, verbatim from `kustomization.yaml`:", ">",
                  "\n".join(f"> {l}" if l else ">" for l in page.header.splitlines()),
                  ""]

    lines += [f"**Source:** [`{page.rel_source}/`](../../{page.rel_source}/)", ""]

    if page.parent:
        lines += [f"**Part of:** [{page.parent}](../{page.parent}.md)", ""]

    if page.namespace:
        lines += [f"**Namespace:** `{page.namespace}`", ""]

    lines += ["### Declared resources", "", bullets(page.resources), ""]

    for key, heading in (("components", "Declared components"),
                         ("transformers", "Transformers"),
                         ("generators", "Generators"),
                         ("validators", "Validators")):
        if page.declared.get(key):
            lines += [f"### {heading}", "", bullets(page.declared[key]), ""]

    if page.kinds:
        lines += ["### Kubernetes kinds", "",
                  ", ".join(f"`{k}`" for k in page.kinds), ""]

    if page.images:
        lines += ["### Container images", "", bullets(page.images), ""]

    if page.remote_refs:
        lines += ["### Remote references", "", bullets(page.remote_refs), ""]

    if page.local_refs:
        entries = []
        for r in page.local_refs:
            link = page.depends_on.get(r)
            note = how_note(page.ref_how[r])
            # Linked when the dependency has a page of its own; bare path when
            # it is a directory the compiler does not turn into a page.
            entries.append(f"- [{link}](../{link}.md){note}" if link else f"- `{r}`{note}")
        lines += ["### Depends on", "", "\n".join(entries), ""]

    if page.patches:
        lines += ["### Patches", "", bullets(page.patches), ""]

    if page.configmaps:
        lines += ["### Generated ConfigMaps", "", bullets(page.configmaps), ""]

    if page.secrets:
        lines += ["### Generated Secrets", "", bullets(page.secrets),
                  "",
                  "_Names only. Values come from overlay `.env` files or SealedSecrets "
                  "and are never recorded here._", ""]

    if page.labels:
        lines += ["### Labels", "",
                  "\n".join(f"- `{k}: {v}`" for k, v in sorted(page.labels.items())), ""]

    if page.consumed_by:
        lines += ["### Consumed by", "",
                  "\n".join(f"- [{c}](../{c}.md){how_note(page.consumed_how[c])}"
                            for c in page.consumed_by), ""]
    elif page.kind == "component":
        lines += ["### Consumed by", "",
                  "_No overlay in this repo references this component._", ""]

    if page.warnings:
        lines += ["### Compiler warnings", "",
                  "\n".join(f"- {w}" for w in page.warnings), ""]

    return "\n".join(lines).rstrip() + "\n"


def existing_summary(path: Path) -> str | None:
    """A one-line summary an agent wrote into frontmatter. Preserved across
    recompiles and used as the page's line in index.md."""
    fm = read_frontmatter(path)
    # Only a summary explicitly marked as authored survives; a derived one is
    # regenerated, otherwise a bad early guess would be frozen forever.
    if fm.get("summary_source") != "authored":
        return None
    value = fm.get("summary")
    return str(value).strip() if value else None


def derive_summary(page: Page) -> str:
    """Fallback one-liner when nobody has written a summary yet."""
    for line in page.header.splitlines():
        line = line.strip()
        # Many kustomizations open with their own path as a comment; that is a
        # filename, not a summary. Skip down to the first line that says something.
        if not line or "kustomization.yaml" in line or line.startswith("k8s/"):
            continue
        return line.rstrip(".")
    if page.images:
        return f"deploys `{page.images[0]}`"
    if page.remote_refs:
        return f"vendors `{page.remote_refs[0].rsplit('/', 1)[-1]}`"
    if page.kinds:
        return "declares " + ", ".join(f"`{k}`" for k in page.kinds[:3])
    if page.local_refs:
        names = [r.rsplit("/", 1)[-1] for r in page.local_refs[:3]]
        return "composes " + ", ".join(f"`{n}`" for n in names)
    if page.resources:
        return f"aggregates {len(page.resources)} resource(s)"
    return "_no summary yet_"


def existing_notes(path: Path) -> str | None:
    """Pull the Notes zone out of an existing page so prose survives a recompile."""
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    idx = text.find(NOTES_HEADING)
    if idx == -1:
        return None
    body = text[idx + len(NOTES_HEADING):].strip("\n")
    return body if body.strip() and body.strip() != NOTES_PLACEHOLDER else None


def render_page(page: Page, compiled_at: str) -> str:
    fm = {
        "title": page.name,
        "kind": page.kind,
        "sources": [page.rel_source],
        "compiled_at": compiled_at,
    }
    if page.category:
        fm["category"] = page.category
    if page.parent:
        fm["parent"] = page.parent
    if page.consumed_by:
        fm["consumed_by"] = page.consumed_by
    last = source_last_commit(page.rel_source)
    if last:
        fm["source_last_commit"] = last
    authored = existing_summary(page.out)
    page.summary = authored or derive_summary(page)
    fm["summary"] = page.summary
    fm["summary_source"] = "authored" if authored else "derived"

    front = yaml.safe_dump(fm, sort_keys=False, default_flow_style=False).strip()
    notes = existing_notes(page.out) or NOTES_PLACEHOLDER

    return (
        f"---\n{front}\n---\n\n"
        f"# {page.name}\n\n"
        f"{DECLARED_BEGIN}\n\n"
        f"{render_declared(page)}\n"
        f"{DECLARED_END}\n\n"
        f"{NOTES_HEADING}\n\n{notes}\n"
    )


def read_concepts() -> list[tuple[str, str, str]]:
    """Concept pages are agent-authored and have no counterpart in k8s/.
    They still belong in the index, so read their title and summary."""
    out = []
    concepts = WIKI / "concepts"
    if not concepts.is_dir():
        return out
    for f in sorted(concepts.glob("*.md")):
        fm = read_frontmatter(f)
        title = str(fm.get("title") or f.stem)
        summary = str(fm.get("summary") or "")
        out.append((title, f"concepts/{f.stem}.md", summary))
    return out


